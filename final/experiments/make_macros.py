"""Turn results/*.csv into LaTeX macros (results/macros.tex) so that the report and the
paper quote measured numbers directly from the data.
    python experiments/make_macros.py
"""
import csv
import json
import os

RES = os.path.join(os.path.dirname(__file__), "..", "results")


def load(name):
    with open(os.path.join(RES, name)) as f:
        return [{k: (float(v) if v.replace(".", "", 1).replace("-", "", 1).isdigit() else v) for k, v in r.items()} for r in csv.DictReader(f)]


def fmt(x, nd=1):
    if isinstance(x, str):
        return x
    if abs(x) >= 1000 and nd <= 1:
        return f"{x:,.0f}".replace(",", "{,}")
    return f"{x:.{nd}f}"


M = {}
e0 = {r["operation"]: r["median_ms"] for r in load("e0_micro.csv")}
M["PairMs"] = fmt(e0["bilinear pairing"]); M["MulMs"] = fmt(e0["G1 scalar multiplication"], 2)
M["SmallMulMs"] = fmt(e0["G1 small (64-bit) multiplication"], 2)
M["PairRatio"] = fmt(json.load(open(os.path.join(RES, "e0_ratio.json")))["pairing_over_mul_median"], 0)   # interleaved, drift-free

e1 = load("e1_availability.csv")
pick = lambda m, a, k: next(r[k] for r in e1 if r["model"] == m and abs(r["A"] - a) < 1e-9)
M["AvailIidHalfOne"] = fmt(pick("iid", 0.5, "base_one_attempt_pct")); M["AvailIidHalfThree"] = fmt(pick("iid", 0.5, "base_three_attempts_pct"))
M["AvailBurstHalfThree"] = fmt(pick("bursty", 0.5, "base_three_attempts_pct"))

e2 = load("e2_latency.csv")
# reference row: largest n measured in one steady machine state (n=120 was re-measured across a speed change)
ref = next(r for r in e2 if r["n"] == 100)
M["Nmax"] = fmt(ref["n"], 0)
M["OursTotalS"] = fmt(ref["ours_total_ms"] / 1000, 2); M["BaseTotalS"] = fmt(ref["base_total_ms"] / 1000, 0)
M["BaseTuavS"] = fmt(ref["base_TUAV_ms"] / 1000, 2); M["BaseTaS"] = fmt(ref["base_TA_ms"] / 1000, 0)
M["PerUavOursMs"] = fmt(ref["ours_total_ms"] / ref["n"], 1); M["PerUavBaseS"] = fmt(ref["base_TA_ms"] / ref["n"] / 1000, 2)
meas = [r["base_total_ms"] / r["ours_total_ms"] for r in e2 if r["n"] <= 100]
cnt = [r["base_TA_est_ms"] / r["ours_est_ms"] for r in e2]
M["MeasRatioLo"], M["MeasRatioHi"] = fmt(min(meas), 0), fmt(max(meas), 0)
M["CountRatioLo"], M["CountRatioHi"] = fmt(min(cnt), 0), fmt(max(cnt), 0)
M["Speedup"] = fmt(sorted(cnt)[len(cnt) // 2], 0)
last = e2[-1]
M["OutlierRatio"] = fmt(last["base_total_ms"] / last["ours_total_ms"], 0)
M["BaseTuavShare"] = fmt(100 * ref["base_TUAV_ms"] / ref["base_total_ms"], 2)

e3 = load("e3_poisoning.csv")
M["PoisonN"] = fmt(json.load(open(os.path.join(RES, "summary.json")))["E3"]["n"], 0)
M["PoisonClean"] = fmt(e3[0]["ours_fallback_ms"] / 1000, 2)
M["PoisonWorst"] = fmt(max(r["ours_fallback_ms"] for r in e3) / 1000, 2)
M["PoisonIndiv"] = fmt(max(r["individual_ms"] for r in e3) / 1000, 2)
M["PoisonGoodTwenty"] = fmt(e3[-1]["ours_goodput_pct"], 0)

e4 = load("e4_bytes.csv"); b = e4[-1]
M["BytesBaseKey"] = fmt(b["base_acks_total_B"] / 1e6, 1); M["BytesOursKey"] = fmt(b["ours_ack_B"] / 1e3, 1)
M["BytesBaseSat"] = fmt(b["base_satellite_B"] / 1e3, 1); M["BytesRatio"] = fmt(b["base_acks_total_B"] / b["ours_ack_B"], 0)
M["ReqBase"] = fmt(b["base_requests_B"] / b["n"], 0); M["ReqOurs"] = fmt(b["ours_requests_B"] / b["n"], 0)

e5 = load("e5_vehicles.csv"); v = e5[-1]
M["VehN"] = fmt(v["vehicles"], 0); M["VehBatchS"] = fmt(v["batch_admit_ms"] / 1000, 1); M["VehIndS"] = fmt(v["individual_verify_ms"] / 1000, 1)
M["VehDropUs"] = fmt(max(r["outsider_bundle_drop_ms"] for r in e5) * 1000, 0)

e6 = {r["side"]: r for r in load("e6_handover.csv")}; mob = load("e6_mobility.csv")[0]
M["HoTuavFull"] = fmt(e6["new TUAV"]["full_readmission_ms"]); M["HoTuavTicket"] = fmt(e6["new TUAV"]["ticket_handover_ms"])
M["HoMemFull"] = fmt(e6["member"]["full_readmission_ms"]); M["HoMemTicket"] = fmt(e6["member"]["ticket_handover_ms"])
M["HoCross"] = fmt(mob["crossings"], 0); M["HoGapFull"] = fmt(mob["gap_full_ms"], 0); M["HoGapTicket"] = fmt(mob["gap_ticket_ms"], 0)
M["HoCpuFull"] = fmt(mob["tuav_cpu_full_s"]); M["HoCpuTicket"] = fmt(mob["tuav_cpu_ticket_s"])

with open(os.path.join(RES, "macros.tex"), "w") as f:
    f.write("% generated by experiments/make_macros.py -- do not edit\n")
    for k, val in M.items():
        f.write(f"\\newcommand{{\\R{k}}}{{{val}}}\n")
print("\n".join(f"{k} = {v}" for k, v in M.items()))
